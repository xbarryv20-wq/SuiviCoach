fun stringsFor(language: AppLanguage): AppStrings =
  when (language) {
    AppLanguage.FR -> FrenchStrings
    AppLanguage.AR -> ArabicStrings
    AppLanguage.EN -> EnglishStrings
  }

fun AppStrings.statusLabel(status: SubscriptionStatus?): String =
  when (status) {
    SubscriptionStatus.ACTIVE -> statusActive
    SubscriptionStatus.EXPIRING_SOON -> statusExpiring
    SubscriptionStatus.EXPIRED -> statusExpired
    null -> statusNoPlan
  }

fun AppStrings.paymentMethodLabel(method: PaymentMethod): String =
  when (method) {
    PaymentMethod.CASH -> methodCash
    PaymentMethod.BARIDIMOB -> methodBaridiMob
    PaymentMethod.CCP -> methodCcp
    PaymentMethod.TRANSFER -> methodTransfer
  }

fun AppStrings.formatDaysRemaining(daysLeft: Int): String =
  when {
    daysLeft == 0 -> expiresToday
    daysLeft == 1 -> expiresTomorrow
    daysLeft > 1 -> daysLeftFormat(daysLeft)
    else -> expiredDaysAgoFormat(-daysLeft)
  }

