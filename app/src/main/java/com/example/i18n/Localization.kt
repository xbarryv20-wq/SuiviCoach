fun formatDA(amount: Int): String {
  val symbols = DecimalFormatSymbols(Locale.FRENCH).apply { groupingSeparator = ' ' }
  val formatter = DecimalFormat("#,##0", symbols)
  return "${formatter.format(amount)} DA"
}

